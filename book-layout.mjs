export function splitPassage(text, limit=94) {
  const words=text.trim().split(/\s+/), chunks=[];
  let current=[];
  for(const word of words) {
    if(current.length && (current.join(' ').length+word.length+1>limit || current.length>=17)) {
      // Prefer an existing sentence or clause boundary near the end.
      let cut=current.length;
      for(let i=current.length-1;i>=Math.floor(current.length*.55);i--) {
        if(/[.!?,;:]$/.test(current[i])){cut=i+1;break;}
      }
      chunks.push(current.slice(0,cut).join(' '));
      current=current.slice(cut);
    }
    current.push(word);
  }
  if(current.length)chunks.push(current.join(' '));
  return chunks;
}

export function prepareReadingPages(pages) {
  return pages.map((page,index)=>({
    ...page,
    layout:sceneLayouts[index],
    beats:page.beats.flatMap((beat,sourceBeat)=>(page.timed?[beat.text]:splitPassage(beat.text)).map((text,part)=>({...beat,text,sourceBeat,part})))
  }));
}

export function overlapsProtected(box, regions, margin=1) {
  // Percentage coordinates can differ by a fraction of a pixel after layout.
  const epsilon=.01;
  return regions.some(region=>box.x<region.x+region.w+margin-epsilon && box.x+box.w>region.x-margin+epsilon && box.y<region.y+region.h+margin-epsilon && box.y+box.h>region.y-margin+epsilon);
}
